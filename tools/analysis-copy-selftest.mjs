import assert from 'node:assert/strict';
import { analysisSummary, analysisSections, analysisSpeech } from '../src/analysisCopy.ts';
assert.equal(analysisSummary({ summary: '不建议食用。配料含葱，与您填写的过敏原相符。配料含葱，与您填写的过敏原相符。', considerations: ['配料含葱，与您填写的过敏原相符。'], uncertainties: ['其他说明不应重复堆叠。'] }), '配料含葱，与您填写的过敏原相符。');
assert.equal(analysisSummary({ summary: '不能排除过敏风险。不能确认可以食用。' }), '不能排除过敏风险。不能确认可以食用。');
assert.equal(analysisSummary({ summary: '配料信息不足；缺失过敏资料。配料信息不足。' }), '配料信息不足；缺失过敏资料。');
assert.equal(analysisSummary({ summary: '不建议食用。', considerations: ['与本人过敏原相符。'] }), '与本人过敏原相符。');
assert.equal(analysisSummary({ summary: '' }), '');
assert.equal(analysisSummary({ summary: '每份含糖2.6克。每份含糖26克。' }), '每份含糖2.6克。每份含糖26克。');
console.log('PASS compact analysis: conclusion not repeated, exact sentence deduplication, negation/limitations preserved, legacy fallback, no invented text');
const five = { formatVersion: 2, recommendation: 'not_recommended', summary: '不建议食用。配料含本人过敏原。配料含本人过敏原。', considerations: ['配料含本人过敏原。', '选择不含该过敏原的食品。'], nutritionAnalysis: [{ nutrient: 'sodium', label: '钠', condition: '高血压', value: 220, unit: 'mg', basis: '每100克', explanation: '结合本人高血压情况关注当天盐分摄入。' }], uncertainties: ['未识别到每份重量，无法换算实际摄入。', '选择不含该过敏原的食品。'] };
const sections = analysisSections(five);
assert.equal(sections.reason, '配料含本人过敏原。');
assert.deepEqual(sections.suggestions, ['选择不含该过敏原的食品。']);
assert.equal(sections.nutrition[0].value, 220);
assert.deepEqual(sections.missing, ['未识别到每份重量，无法换算实际摄入。']);
assert.deepEqual(analysisSections({ ...five, nutritionAnalysis: [], uncertainties: [] }).nutrition, []);
assert.deepEqual(analysisSections({ summary: '旧记录原因。', considerations: ['旧版其他说明。'] }).suggestions, []);
const speech = analysisSpeech(five);
assert(speech.includes('具体建议') && speech.includes('相关营养分析') && speech.includes('信息不足说明'));
assert.equal(speech.match(/选择不含该过敏原的食品/g).length, 1);
assert.equal(speech.match(/不建议食用/g).length, 1);
console.log('PASS five-part analysis: distinct reason/action, evidence-backed nutrition, conditional missing info, cross-section deduplication, legacy compatibility, matching speech');
