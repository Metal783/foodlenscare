import assert from 'node:assert/strict';
import { diseaseReminders } from '../src/diseaseReminders.ts';
let count = 0;
const check = (condition, title) => { assert.ok(condition, title); count++; console.log('PASS ' + title); };
const diabetes = label => diseaseReminders(label, ['diabetes'])[0].message;
check(diseaseReminders({}, []).length === 0, '没有基础疾病不生成虚构疾病提醒');
check(diabetes({}).includes('糖含量未确认'), '糖尿病且糖缺失时明确提醒');
check(!diabetes({ nutritionPer100g: { sugar: 0 } }).includes('糖0克'), '未确认的普通数值不冒充已核对');
check(diabetes({ ingredientText: '小麦粉、白砂糖' }).includes('疑似含「白砂糖」'), '糖配料作为待核对证据');
check(!diabetes({ ingredientText: '赤藓糖醇' }).includes('疑似含'), '不把糖醇名称误判成白砂糖');
const candidate = { servingUnit: 'g', servingLabel: '每100克', nutritionCandidates: { sugar: { value: 18, confidence: .9 } } };
check(diabetes(candidate).includes('OCR候选，尚未核对：每100克糖18克'), '糖候选明确标为OCR未核对');
check(diabetes({ ...candidate, nutritionCandidates: { sugar: { value: 18, confidence: .5 } } }).includes('糖含量未确认'), '低置信度糖值不展示为可靠数值');
check(diabetes({ ...candidate, nutritionCandidates: { sugar: { value: 18, confidence: .9, conflict: true } } }).includes('糖含量未确认'), '冲突糖候选不能使用');
check(diabetes({ ...candidate, servingUnit: null }).includes('糖含量未确认'), '口径不明确不能给每100克糖值');
check(diabetes({ ...candidate, nutritionCandidates: { sugar: { value: -1, confidence: .9 } } }).includes('糖含量未确认'), '拒绝负数糖值');
check(diabetes({ ...candidate, servingUnit: 'ml', servingLabel: '每100毫升' }).includes('每100毫升糖18克'), '保留每100毫升口径');
check(diabetes({ nutritionConfirmed: true, servingLabel: '每100克', nutritionPer100g: { sugar: 0, carbohydrate: 30 } }).includes('已核对：每100克糖0克'), '已核对零值可以如实显示');
check(diabetes({ nutritionConfirmed: true, nutritionPer100g: { carbohydrate: 30 } }).includes('糖含量未确认'), '碳水值不当作糖值');
check(diseaseReminders({}, ['hypertension'])[0].message.includes('钠含量未确认'), '高血压匹配钠提醒');
check(diseaseReminders({}, ['hyperlipidemia'])[0].message.includes('饱和脂肪'), '高血脂匹配脂肪提醒');
check(diseaseReminders({}, ['coronary'])[0].title.includes('冠心病'), '冠心病显示资料核对提醒');
check(diseaseReminders({}, ['diabetes', 'hypertension', 'hyperlipidemia']).length === 3, '多基础疾病可以同时提醒');
check(diabetes(candidate).includes('不能据此计算摄入量'), '提醒不会替代实际食用确认');
console.log(`基础疾病提醒：${count}项通过`);
