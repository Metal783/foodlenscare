import assert from 'node:assert/strict';
import { labelChecklist } from '../src/labelCheckItems.ts';
let count = 0;
const check = (value, message) => { assert(value, message); count++; };
const base = { ingredientText: '小麦粉、食盐', declaredPer: 'per100g', servingLabel: '每100克', nutritionPer100g: { sodium: 220, sugar: 0 }, confidence: { sodium: .99, sugar: .9 } };
const item = (label, id) => labelChecklist(label).find(row => row.id === id);
check(!item(base, 'sugar').needsCheck, '真实零值是候选，不是缺失');
check(!item(base, 'sodium').needsCheck, '可靠钠候选');
check(item(base, 'protein').needsCheck && item(base, 'protein').note.includes('不能当作零'), '缺失不补零');
check(item({}, 'ingredients').needsCheck, '空标签可以生成补拍提醒');
check(!item(base, 'ingredients').needsCheck, '配料可读不代表核对完成');
check(item(base, 'allergens').note.includes('不代表没有过敏原'), '缺声明不声称无过敏原');
check(!item({ ...base, allergenDeclaration: '可能含有乳' }, 'allergens').needsCheck, '声明已读到仍需核对');
check(item({ ...base, confidence: {} }, 'sodium').needsCheck, '无置信依据');
for (const confidence of [.69, 1.01, NaN, Infinity, true, '0.99']) check(item({ ...base, confidence: { sodium: confidence } }, 'sodium').needsCheck, '无效置信依据');
check(!item({ ...base, confidence: { sodium: .7 } }, 'sodium').needsCheck, '置信边界');
for (const sodium of [-1, Infinity, NaN, true, '220', 100001]) check(item({ ...base, nutritionPer100g: { sodium } }, 'sodium').needsCheck, '无效候选不变为可信');
check(item({ ...base, nutritionCandidates: { sodium: { confidence: .99, conflict: true } } }, 'sodium').note.includes('冲突'), '冲突单独提示');
check(item({ ...base, nutritionCandidates: { sodium: { confidence: .99, warning: 'unit' } } }, 'sodium').note.includes('单位'), '单位问题单独提示');
check(item({ ...base, servingLabel: '每份' }, 'basis').needsCheck, '口径标签不一致');
check(item({ ...base, declaredPer: 'unknown' }, 'basis').needsCheck, '口径未知');
check(!item({ ...base, servingLabel: '每100毫升' }, 'basis').needsCheck, '毫升口径');
const portion = { ...base, declaredPer: 'perServing', servingLabel: '每份（50g）', nutritionPerServing: { sodium: 90 } };
check(!item(portion, 'basis').needsCheck && !item(portion, 'sodium').needsCheck, '明确每份重量');
check(item({ ...portion, servingLabel: '每份' }, 'sodium').note.includes('口径'), '有数字但无每份重量需先核对表头');
for (const servingLabel of ['每份（0g）', '每份（100001g）', '每100克，另含每份']) check(item({ ...portion, servingLabel }, 'basis').needsCheck, '无效/混合口径');
const original = JSON.stringify(base); labelChecklist(base); check(JSON.stringify(base) === original, '不修改识别输入');
check(item(base, 'storage').note.includes('未自动读取'), '保质期不伪造识别');
console.log(`PASS ${count} label-checklist evidence checks`);
